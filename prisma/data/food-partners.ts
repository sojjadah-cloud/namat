/**
 * NAMAT food partners — Muscat.
 *
 * Field research, not confirmed commercial agreements: being listed here means
 * the business was found and described, not that it has signed with NAMAT.
 * `status` carries that distinction and nothing should be shown publicly as a
 * partner until it reads `PARTNER`.
 *
 * ── Why so many nulls ─────────────────────────────────────────────────────
 * A boolean can say "delivers" or "does not deliver". Most of this research
 * says neither — it says "not verified". Collapsing that to `false` would make
 * the "delivers to me" filter hide businesses that very likely do deliver,
 * and the app would look confident while being wrong. So every operational
 * capability is `boolean | null`, where `null` means unverified, and the
 * filters treat unknown as "do not exclude, but rank below confirmed".
 *
 * ── Coordinates ───────────────────────────────────────────────────────────
 * `coordsVerified: false` marks a position taken from a search result rather
 * than confirmed on the map. Those are safe to sort by but must not be used
 * for turn-by-turn directions until checked.
 */

export type Confidence = 'CONFIRMED' | 'LIKELY' | 'UNVERIFIED';

export type PartnerStatus =
  /** Researched only. Not contacted, not signed. */
  | 'PROSPECT'
  /** Reference business used to shape the category. Never shown as a partner. */
  | 'BENCHMARK';

export type FoodTag =
  | 'MEALS'
  | 'SUBSCRIPTIONS'
  | 'HIGH_PROTEIN'
  | 'KETO'
  | 'LOW_CARB'
  | 'VEGETARIAN'
  | 'SALADS'
  | 'JUICES'
  | 'BAKERY'
  | 'GROCERY';

/** How much of the menu is actually health-oriented. */
export type MenuProfile =
  /** Everything on the menu fits the category. */
  | 'DEDICATED'
  /** Mostly health-oriented, some regular items. */
  | 'MOSTLY'
  /** A health section inside an otherwise conventional menu. */
  | 'MIXED';

export type FoodPartner = {
  slug: string;
  nameEn: string;
  nameAr: string | null;
  area: string;
  address: string | null;
  lat: number | null;
  lng: number | null;
  coordsVerified: boolean;
  phone: string | null;
  tags: FoodTag[];
  menuProfile: MenuProfile;
  /** null = not verified either way. See the note at the top of this file. */
  ownDelivery: boolean | null;
  platformDelivery: boolean | null;
  pickup: boolean | null;
  weeklyPlan: boolean | null;
  monthlyPlan: boolean | null;
  caloriesLabelled: boolean | null;
  proteinLabelled: boolean | null;
  /** Internal ranking from the research, A+ down to C. Not shown to members. */
  priority: 'A_PLUS' | 'A' | 'B_PLUS' | 'B' | 'C_PLUS' | 'C';
  confidence: Confidence;
  status: PartnerStatus;
  notes?: string;
};

